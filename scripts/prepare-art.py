#!/usr/bin/env python3
"""
prepare-art.py — turns generated views into site-ready panoramas and wires them up.

  1. Save each generated image into art/raw/ named after its view id (see below).
  2. Run:  python3 scripts/prepare-art.py
  3. It writes art/panos/*.webp and REWRITES js/assets.js. Nothing else to wire.

Each image is detected automatically:
  • 2:1 image (e.g. 4096×2048, from a 360° generator)  → full look-around panorama
  • any other wide image (16:9, 21:9 …)                  → "flat" view you can look around within its edges

View ids (file stems in art/raw/):
  stops:   popolo colosseum aqueducts forum pantheon circus vatican bocca capitoline spanish campo trevi
  streets: via-del-corso via-appia fori-imperiali via-del-seminario via-dei-cerchi ponte-sant-angelo
           lungotevere teatro-marcello via-condotti via-giubbonari via-delle-muratte

Requires: pip install pillow
"""
import json, sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    sys.exit("Install Pillow first:  pip install pillow")

ROOT = Path(__file__).resolve().parent.parent
RAW, OUT, ASSETS_JS = ROOT / "art" / "raw", ROOT / "art" / "panos", ROOT / "js" / "assets.js"
STOPS = ["popolo", "colosseum", "aqueducts", "forum", "pantheon", "circus", "vatican", "bocca", "capitoline", "spanish", "campo", "trevi"]
STREETS = ["via-del-corso", "via-appia", "fori-imperiali", "via-del-seminario", "via-dei-cerchi", "ponte-sant-angelo",
           "lungotevere", "teatro-marcello", "via-condotti", "via-giubbonari", "via-delle-muratte"]
IDS = STOPS + STREETS
EXTS = (".png", ".jpg", ".jpeg", ".webp")
PANO_W, FLAT_W = 4096, 3200   # 4096×2048 keeps panoramas sharp without huge downloads


def main():
    if not RAW.exists():
        RAW.mkdir(parents=True)
        sys.exit("Created art/raw/ — put your generated images there and run again.")
    files = {p.stem.lower(): p for p in RAW.iterdir() if p.suffix.lower() in EXTS}
    if not files:
        sys.exit("art/raw/ is empty.")
    OUT.mkdir(parents=True, exist_ok=True)
    panos, unknown = {}, []
    for stem, path in sorted(files.items()):
        if stem not in IDS:
            unknown.append(path.name); continue
        im = Image.open(path).convert("RGB")
        ratio = im.width / im.height
        pano = 1.9 <= ratio <= 2.1
        if ratio < 1.2:
            print(f"✗ {path.name}: {im.width}×{im.height} is too narrow. Generate a wide (16:9+) or 360° (2:1) image."); continue
        target = PANO_W if pano else FLAT_W
        if im.width > target:
            im = im.resize((target, round(target / ratio)), Image.LANCZOS)
        if pano and im.height * 2 != im.width:                      # exact 2:1 for clean wrapping
            im = im.resize((im.width, im.width // 2), Image.LANCZOS)
        out = OUT / f"{stem}.webp"
        im.save(out, "WEBP", quality=84, method=6)
        kb = out.stat().st_size // 1024
        entry = {"src": f"art/panos/{stem}.webp", "type": "pano" if pano else "flat"}
        if not pano:
            entry["hfov"] = 110                                         # wide enough to turn your head; 90 clamps a 16:9 plate to a tunnel
        panos[stem] = entry
        warn = "  ⚠ large, consider fewer details or a lower size" if kb > 2500 else ""
        print(f"  ✓ {stem:<20} {'360° panorama' if pano else 'wide view':<14} {im.width}×{im.height}  {kb} KB{warn}")

    header = ("/* AUTO-GENERATED by scripts/prepare-art.py — re-run the script instead of editing.\n"
              "   Views not listed here use the built-in placeholder. */\nwindow.Rome = window.Rome || {};\n")
    ASSETS_JS.write_text(header + "Rome.ASSETS = " + json.dumps({"panos": panos}, indent=2) + ";\n", encoding="utf-8")
    print(f"\n✓ Wrote js/assets.js ({len(panos)} views)")
    missing = [i for i in IDS if i not in panos]
    if missing:
        print(f"  Still placeholders: {', '.join(missing)}")
    if unknown:
        print(f"  ⚠ Ignored (not a view id): {', '.join(unknown)}")
    print("\nNext: npm run serve → open http://localhost:8765/?edit=1 → set arrows + markers → paste into js/data.js → npm test")


if __name__ == "__main__":
    main()
